"""Канонизация имени класса материала: латиница/кириллица, разделитель, пробелы."""
import pytest

from crud.materials import normalize_class_name


@pytest.mark.parametrize(("raw", "expected"), [
    ("В25", "В25"),            # уже канон
    ("B25", "В25"),            # латинская B → кириллическая В
    ("B60", "В60"),
    ("В7,5", "В7.5"),          # запятая → точка
    ("B7.5", "В7.5"),
    ("В 25", "В25"),           # пробел между буквой и числом
    (" В25 ", "В25"),
    ("в25", "В25"),            # первая буква — заглавная
    ("A500C", "А500С"),        # латиница в префиксе и суффиксе
    ("А500 С", "А500С"),
    ("A240", "А240"),
    ("M200", "М200"),
    ("Ат800", "Ат800"),        # регистр ГОСТ-обозначения сохраняется
])
def test_class_codes_are_canonicalized(raw, expected):
    """Коды классов (буквы + число + суффикс) приводятся к единому кириллическому виду."""
    assert normalize_class_name(raw) == expected


@pytest.mark.parametrize(("raw", "expected"), [
    ("Цементное молоко", "Цементное молоко"),
    ("  Проволока   вязальная ", "Проволока вязальная"),  # только схлопывание пробелов
    ("С-3", "С-3"),                                        # добавка с дефисом — не код класса
    ("Penetron Admix", "Penetron Admix"),                  # латинское торговое имя не трогаем
    ("B25 W8 F200", "B25 W8 F200"),                        # полная спецификация — не код
])
def test_non_code_names_only_collapse_whitespace(raw, expected):
    """Не-коды (добавки, exclude-имена, торговые марки) не транслитерируются."""
    assert normalize_class_name(raw) == expected
